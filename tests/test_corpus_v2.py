def _bench_collision_file() -> str:
    from neurobrain.codebench_tasks import TASKS
    t = TASKS[0]
    return '"""sneaky."""\n\n\n' + t["prompt"] + t["reference"] + "\n\n\ndef other_helper(q):\n    \"\"\"double the given number and add one to the result\"\"\"\n    return q * 2 + 1\n"


def _pad(content: str, min_bytes: int = 520) -> str:
    """real corpus files are >=400B; pad the synthetic ones the same way."""
    i = 0
    while len(content.encode()) < min_bytes:
        content += f"# filler line {i} to reach the corpus minimum file size\n"
        i += 1
    return content


def _write(tmp_path, name, content):
    (tmp_path / name).write_text(_pad(content))


def test_build_pipeline(tmp_path):
    root = tmp_path / "root"
    root.mkdir()
    _write(root, "good.py", GOOD)
    _write(root, "dup.py", DUP)
    _write(root, "bad.py", BAD_SYNTAX)
    _write(root, "gen.py", GENERATED)
    _write(root, "mini.py", MINIFIED)
    _write(root, "bench.py", _bench_collision_file())
    vendor = root / "vendor"
    vendor.mkdir()
    _write(vendor, "v.py", GOOD.replace("good helpers", "vendored helpers"))

    out = tmp_path / "out"
    rep = cv2.build([str(root)], str(out), TOK_PATH, seed=3, cap_per_cat=100,
                    report_path=str(tmp_path / "rep.json"), val_floor=1, pack_bytes=120)

    assert rep["drop"].get("syntax", 0) == 1, "unparseable file must be dropped"
    assert rep["drop"].get("generated_marker", 0) == 1, "AUTO-GENERATED file must be dropped"
    assert rep["drop"].get("minified_like", 0) == 1, "long-line file must be dropped"
    assert rep["drop"].get("vendored_or_fixture", 0) == 1, "vendor/ dir must be dropped"
    assert rep["units_drop"].get("holdout", 0) >= 1, "codebench collision must be excluded"
    assert rep["units_drop"].get("dup_source", 0) >= 1 or rep["units_drop"].get("dup_ast", 0) >= 1, \
        "cosmetic duplicate must be deduped"
    assert rep["instruction_candidates"] >= 3, "docstring units become instruction episodes"
    assert os.path.exists(tmp_path / "rep.json")
    assert json.load(open(tmp_path / "rep.json"))["files_parsed"] == 3  # good.py + dup.py + bench.py

    # bins: valid uint16 streams that decode back to the expected formats
    tok = BPETokenizer.load(TOK_PATH)
    train = np.memmap(out / "code_train_v2.bin", dtype=np.uint16, mode="r")
    text = tok.decode(train.tolist())
    assert "<|task|>write a function that" in text, "instruction episodes must be in the train stream"
    assert "<|code|>" in text
    assert "def greet_person" in text, "kept units must be in the train stream"
    assert "def add(a, b)" not in text, "codebench task source must NOT be in the stream"
    assert "register_all" not in text, "generated file content must NOT be in the stream"
    val_p = np.memmap(out / "code_val_v2_plain.bin", dtype=np.uint16, mode="r")
    val_i = np.memmap(out / "code_val_v2_instr.bin", dtype=np.uint16, mode="r")
    assert len(val_p) > 0 and len(val_i) > 0
    eot = tok.special_id("<|fim_middle|>")
    assert train[-1] == eot and val_p[-1] == eot, "streams end on <|fim_middle|>"
    assert rep["tokens"]["code_train_v2"] == len(train)


def test_instruction_format():
    u = {"source": "def f(x):\n    return x\n", "name": "f", "kind": "function",
         "cat": "misc", "doc": "double the given number"}
    ep = cv2.make_instruction(u)
    assert ep == "<|task|>write a function that double the given number<|code|>\ndef f(x):\n    return x\n\n"
    assert cv2.make_instruction({**u, "doc": None}) is None
    # a docstring that merely restates the name is not an instruction
    assert cv2.make_instruction({**u, "doc": "f the thing"}) is None
