"""Corpus v2 (agent 04, deliverables 2 + 6): function-level code corpus.

Pipeline, one stage per concern, everything counted and reported:

  walk roots -> read .py -> ast.parse (drop unparseable)
  -> drop generated / vendored / fixture / minified files (heuristics)
  -> split into top-level function/class units (80..6000 bytes)
  -> dedupe by normalized-source sha1 AND by AST-dump sha1
  -> exclude codebench collisions verbatim (held out by hash + content)
  -> classify into categories, cap per category (balance)
  -> plain stream: units packed with the <|code|> special up to ~1800 bytes
  -> instruction stream: units with usable docstrings become
     "<|task|>write a function that <summary><|code|>\\n<unit>\\n"
  -> mix so instruction tokens are ~20% of code tokens (deliverable 6)
  -> 3% of documents held out for val; val ALSO split plain-vs-instructed
     so the two formats can be evaluated separately
  -> stream uint16 bins to disk (flat RSS on a 2 GB box)

Tokenizer is the existing 2052-token BPE (checkpoint compatible); the special
strings <|task|>/<|code|> are plain text to it, exactly as drive.py uses them.
A 4096-token code-only tokenizer is a separate later experiment.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import random
import sys
import time

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

GEN_MARKERS = ("autogenerated", "auto-generated", "generated by", "do not edit",
               "machine-generated", "this file is generated")
VENDOR_PARTS = {"vendor", "vendored", "_vendor", "fixtures", "fixture", "generated",
                "autogen", "testdata", "test_data", "samples", "examples"}
SKIP_PARTS = {"__pycache__", ".git", "node_modules", "tests", "test"}

MIN_UNIT = 80
MAX_UNIT = 6000
PACK_BYTES = 1800
INSTR_SHARE = 0.20

CAT_RULES = [
    ("io", ("io", "file", "path", "read", "write", "stream", "buffer", "open", "csv", "tar", "zip", "gzip", "pickle")),
    ("net", ("socket", "http", "url", "net", "request", "client", "server", "mail", "ssl", "select", "connection")),
    ("text", ("string", "text", "regex", "format", "parse", "token", "encod", "decod", "unicod", "html", "xml", "json", "re.", "difflib")),
    ("numeric", ("math", "numeric", "number", "decimal", "fraction", "random", "stat", "complex", "cmath", "bit")),
    ("data", ("collection", "data", "list", "dict", "set", "queue", "heap", "enum", "typing", "struct", "array", "copy", "pprint")),
    ("os_sys", ("os", "sys", "process", "term", "platform", "env", "subprocess", "shutil", "glob", "posix", "getpass", "errno")),
    ("time_date", ("time", "date", "calendar", "sched", "datetime", "zoneinfo")),
    ("concurrency", ("thread", "concurrent", "async", "await", "multiprocess", "lock", "pool", "future", "coroutine")),
    ("runtime", ("import", "module", "inspect", "types", "functools", "itertools", "abc", "context", "warn", "trace", "weakref", "gc", "attr", "decorator", "class")),
]


def _cat_of(relpath: str, head: str) -> str:
    text = (relpath + " " + head).lower()
    best, best_hits = "misc", 0
    for cat, kws in CAT_RULES:
        hits = sum(1 for k in kws if k in text)
        if hits > best_hits:
            best, best_hits = cat, hits
    return best


def _norm(s: str) -> str:
    return " ".join(s.split())


def _sha1(s: str) -> str:
    return hashlib.sha1(s.encode("utf-8", "ignore")).hexdigest()


def _file_flags(path: str, rel: str, src: str) -> str | None:
    """Why this file should be dropped, or None to keep."""
    parts = {p.lower() for p in rel.split(os.sep)}
    if parts & VENDOR_PARTS:
        return "vendored_or_fixture"
    head = src[:2048].lower()
    if any(m in head for m in GEN_MARKERS):
        return "generated_marker"
    lines = src.splitlines()[:200]
    if lines:
        long_frac = sum(1 for l in lines if len(l) > 160) / len(lines)
        if long_frac > 0.3:
            return "minified_like"
    return None


def _doc_summary(node: ast.AST) -> str | None:
    doc = ast.get_docstring(node)  # type: ignore[arg-type]
    if not doc:
        return None
    first = doc.strip().split("\n\n")[0].strip()
    first = first.split("\n")[0].strip()
    if first.endswith("."):
        first = first[:-1]
    first = _norm(first)
    if len(first.split()) < 3 or len(first) > 140:
        return None
    if first[:4].lower() in ("self", "cls "):
        return None
    return first


def iter_units(roots: list[str], report: dict, holdout_needles: set[str]):
    """Yield dicts: {source, name, kind, cat, doc} for every kept unit."""
    seen_src: set[str] = set()
    seen_ast: set[str] = set()
    for root in roots:
        for dp, dn, fn in os.walk(root):
            rel_dir = os.path.relpath(dp, root)
            keep = [d for d in dn if d not in SKIP_PARTS and not d.startswith(".")]
            dn[:] = keep
            for name in fn:
                if not name.endswith(".py"):
                    continue
                p = os.path.join(dp, name)
                rel = os.path.join(rel_dir, name)
                report["files"] += 1
                try:
                    if not (400 <= os.path.getsize(p) <= 400_000):
                        report["drop"]["size"] += 1
                        continue
                    with open(p, encoding="utf-8", errors="ignore") as f:
                        src = f.read()
                except OSError:
                    report["drop"]["unreadable"] += 1
                    continue
                flag = _file_flags(p, rel, src)
                if flag:
                    report["drop"][flag] += 1
                    continue
                try:
                    tree = ast.parse(src)
                except SyntaxError:
                    report["drop"]["syntax"] += 1
                    continue
                report["files_parsed"] += 1
                cat = _cat_of(rel, src[:1024])
                for node in tree.body:
                    if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                        continue
                    try:
                        seg = ast.get_source_segment(src, node)
                    except Exception:  # noqa: BLE001
                        seg = None
                    if seg is None or not (MIN_UNIT <= len(seg) <= MAX_UNIT):
                        report["units_drop"]["size"] += 1
                        continue
                    h_src = _sha1(_norm(seg))
                    h_ast = _sha1(ast.dump(node, annotate_fields=False, include_attributes=False))
                    if h_src in seen_src:
                        report["units_drop"]["dup_source"] += 1
                        continue
                    if h_ast in seen_ast:
                        report["units_drop"]["dup_ast"] += 1
                        continue
                    if h_src in holdout_needles:
                        report["units_drop"]["holdout"] += 1
                        continue
                    seen_src.add(h_src)
                    seen_ast.add(h_ast)
                    kind = "class" if isinstance(node, ast.ClassDef) else "function"
                    yield {"source": seg.rstrip() + "\n", "name": node.name, "kind": kind,
                           "cat": cat, "doc": _doc_summary(node)}


def make_instruction(u: dict) -> str | None:
    if not u["doc"] or u["doc"].lower().startswith(u["name"].lower()):
        return None
    return f"<|task|>write a {u['kind']} that {u['doc']}<|code|>\n{u['source']}\n"


def build(roots: list[str], out_dir: str, tokenizer_path: str, seed: int = 11,
          cap_per_cat: int = 12000, max_units: int = 400000,
          report_path: str | None = None, val_floor: int = 16,
          pack_bytes: int = PACK_BYTES) -> dict:
    from neurobrain.tokenizer import BPETokenizer

    tok = BPETokenizer.load(tokenizer_path)
    eot = tok.special_id("<|fim_middle|>")
    pack_sep = "<|code|>"
    rng = random.Random(seed)

    # holdout: codebench task sources must never appear in training
    needles: set[str] = set()
    try:
        from neurobrain.codebench_tasks import TASKS
        for t in TASKS:
            needles.add(_sha1(_norm(t["prompt"] + t["reference"])))
    except Exception:  # noqa: BLE001
        pass

    report = {"files": 0, "files_parsed": 0, "drop": {}, "units_drop": {},
              "units_kept": 0, "categories": {}, "seed": seed}

    units = []
    for u in iter_units(roots, report, needles):
        report["units_kept"] += 1
        report["categories"][u["cat"]] = report["categories"].get(u["cat"], 0) + 1
        units.append(u)
        if len(units) >= max_units:
            break

    # balance: cap per category
    by_cat: dict[str, list[dict]] = {}
    for u in units:
        by_cat.setdefault(u["cat"], []).append(u)
    kept: list[dict] = []
    for cat, lst in sorted(by_cat.items()):
        rng.shuffle(lst)
        kept.extend(lst[:cap_per_cat])
    report["units_balanced"] = len(kept)
    report["categories_capped"] = {c: min(len(l), cap_per_cat) for c, l in sorted(by_cat.items())}
    rng.shuffle(kept)

    # documents: plain packs + instruction episodes
    plain_docs: list[str] = []
    pack: list[str] = []
    pack_len = 0
    for u in kept:
        s = u["source"]
        pack.append(s)
        pack_len += len(s)
        if pack_len >= pack_bytes:
            plain_docs.append(pack_sep.join(pack))
            pack, pack_len = [], 0
    if pack:
        plain_docs.append(pack_sep.join(pack))

    instr_docs: list[str] = []
    for u in kept:
        ep = make_instruction(u)
        if ep:
            instr_docs.append(ep)
    rng.shuffle(instr_docs)
    report["instruction_candidates"] = len(instr_docs)

    def write_stream(path: str, docs: list[str], tag: str) -> int:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        total, buf = 0, []
        with open(path, "wb") as f:
            for i, d in enumerate(docs):
                buf.extend(tok.encode(d))
                buf.append(eot)
                if len(buf) >= 1_000_000:
                    np.array(buf, dtype=np.uint16).tofile(f)
                    total += len(buf)
                    buf = []
                    print(f"[corpus-v2] {tag}: {i+1}/{len(docs)} docs, {total/1e6:.2f}M tokens", flush=True)
            if buf:
                np.array(buf, dtype=np.uint16).tofile(f)
                total += len(buf)
        print(f"[corpus-v2] {tag}: {total/1e6:.2f}M tokens -> {path}", flush=True)
        return total

    # val split by document (3%), plain and instructed kept separate for eval
    rng.shuffle(plain_docs)
    n_val = max(val_floor, int(0.03 * len(plain_docs)))
    n_val = min(n_val, max(1, len(plain_docs) // 3))
    val_plain, train_plain = plain_docs[:n_val], plain_docs[n_val:]
    n_val_i = max(val_floor, int(0.03 * len(instr_docs))) if instr_docs else 0
    n_val_i = min(n_val_i, max(1, len(instr_docs) // 3)) if instr_docs else 0
    val_instr, train_instr = instr_docs[:n_val_i], instr_docs[n_val_i:]

    # trim instruction stream to ~INSTR_SHARE of code tokens
    est_plain_tok = sum(len(tok.encode(d)) + 1 for d in train_plain[:2000]) / max(1, len(train_plain[:2000])) * len(train_plain)
    budget = int(INSTR_SHARE / (1 - INSTR_SHARE) * est_plain_tok)
    acc = 0
    cut = len(train_instr)
    for i, d in enumerate(train_instr):
        acc += len(tok.encode(d)) + 1
        if acc > budget:
            cut = i
            break
    train_instr = train_instr[:cut]
    # interleave: shuffle the doc order of the mixed train stream
    train_docs = train_plain + train_instr
    rng.shuffle(train_docs)

    counts = {
        "code_train_v2": write_stream(os.path.join(out_dir, "code_train_v2.bin"), train_docs, "train"),
        "code_val_v2_plain": write_stream(os.path.join(out_dir, "code_val_v2_plain.bin"), val_plain, "val-plain"),
        "code_val_v2_instr": write_stream(os.path.join(out_dir, "code_val_v2_instr.bin"), val_instr, "val-instr"),
    }
    instr_tokens = sum(len(tok.encode(d)) + 1 for d in train_instr)
    total_tokens = counts["code_train_v2"]
    raw_bytes = sum(len(u["source"].encode()) for u in kept)
    report.update({
        "tokens": counts,
        "train_plain_docs": len(train_plain), "train_instr_docs": len(train_instr),
        "instr_share_est": round(instr_tokens / max(1, total_tokens), 4),
        "unit_bytes": raw_bytes,
        "bytes_per_token": round(raw_bytes / max(1, total_tokens), 3),
        "built_utc": time.strftime("%FT%TZ", time.gmtime()),
    })
    if report_path:
        os.makedirs(os.path.dirname(report_path) or ".", exist_ok=True)
        with open(report_path, "w") as f:
            json.dump(report, f, indent=1)
    return report


def main() -> None:
    ap = argparse.ArgumentParser(description="build corpus v2")
    ap.add_argument("--out", default=os.path.join(ROOT, "data"))
    ap.add_argument("--tokenizer", default=os.path.join(ROOT, "data", "tokenizer.json"))
    ap.add_argument("--report", default=os.path.join(ROOT, "reports", "corpus_v2_report.json"))
    ap.add_argument("--cap-per-cat", type=int, default=12000)
    ap.add_argument("--max-units", type=int, default=400000)
    ap.add_argument("--seed", type=int, default=11)
    args = ap.parse_args()

    import sysconfig
    roots = [sysconfig.get_paths()["stdlib"], sysconfig.get_paths()["purelib"]]
    t0 = time.time()
    rep = build(roots, args.out, args.tokenizer, seed=args.seed,
                cap_per_cat=args.cap_per_cat, max_units=args.max_units,
                report_path=args.report)
    print(json.dumps({k: rep[k] for k in ("files", "files_parsed", "units_kept",
                                          "units_balanced", "tokens", "instr_share_est",
                                          "bytes_per_token")}, indent=1))
    print(f"[corpus-v2] done in {time.time()-t0:.0f}s")


if __name__ == "__main__":
    main()
